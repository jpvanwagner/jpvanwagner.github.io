// Rebuilds js/patron-models.js: the 3D view's patron figures, Kenney "Mini Characters 1"
// (CC0, kenney.nl/assets/mini-characters). Downloads the pack's GLBs (from a GitHub mirror,
// pinned to a commit), embeds the shared texture, drops what the viewer doesn't use
// (tangents, the second UV set, all animations but idle/walk/sit/wheelchair, which are kept
// once, in `anims`: every character shares one skeleton), quantizes, and writes the GLBs
// into one script as base64, so the 3D view also works when the game is opened from disk.
//
//   npm install @gltf-transform/core@4 @gltf-transform/extensions@4 @gltf-transform/functions@4
//   node tools/build-patrons.mjs
//
// Which figure plays which audience is set in CAST in js/viewer3d.js.
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { prune, quantize, dedup } from '@gltf-transform/functions';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const BASE = 'https://raw.githubusercontent.com/ivanlarios22/Zapopan/913e7643e99e8e749fd8e17f4f7de19ef8597b43/Characters/Models/GLB%20format/';
const KEEP = new Set(['idle', 'walk', 'sit', 'wheelchair-sit', 'wheelchair-move-forward']);
const MODELS = ['female-a', 'female-b', 'female-c', 'female-d', 'female-f', 'male-a', 'male-b', 'male-d', 'male-e', 'male-f'];

const io = new NodeIO(fetch).registerExtensions(ALL_EXTENSIONS).setAllowNetwork(true);
async function pack(file, keepAnims) {
  const doc = await io.read(BASE + file);   // also fetches the shared Textures/colormap.png
  const root = doc.getRoot();
  root.listAnimations().forEach(a => {
    if (keepAnims && KEEP.has(a.getName())) return;
    a.listSamplers().forEach(s => { [s.getInput(), s.getOutput()].forEach(x => x && x.dispose()); s.dispose(); });
    a.listChannels().forEach(c => c.dispose());
    a.dispose();
  });
  root.listTextures().forEach(t => t.setURI(''));   // embed the texture in the GLB
  // the texture transform only restates UV set 0; three r128 warns about it, so drop it
  root.listMaterials().forEach(m => { const ti = m.getBaseColorTextureInfo(); if (ti) ti.setExtension('KHR_texture_transform', null); });
  root.listExtensionsUsed().forEach(e => { if (e.extensionName === 'KHR_texture_transform') e.dispose(); });
  // the viewer uses plain lit materials: no tangents or second UV set needed
  root.listMeshes().forEach(m => m.listPrimitives().forEach(p => ['TANGENT', 'TEXCOORD_1'].forEach(s => { if (p.getAttribute(s)) p.setAttribute(s, null); })));
  await doc.transform(prune(), dedup(), quantize());
  return Buffer.from(await io.writeBinary(doc)).toString('base64');
}
const out = {};
for (const m of MODELS) out[m] = await pack('character-' + m + '.glb', false);
out.anims = await pack('character-female-a.glb', true);
out.cane = await pack('aid-cane.glb', false);
out.glasses = await pack('aid-glasses.glb', false);
out.wheelchair = await pack('wheelchair.glb', false);
const js = '/* JS/PATRON-MODELS.JS - GENERATED by tools/build-patrons.mjs (see README). Don\'t edit by hand.\n' +
  '   Kenney "Mini Characters 1" (CC0 1.0, kenney.nl/assets/mini-characters): ten patrons plus a cane,\n' +
  '   glasses and a wheelchair, as base64 GLB. `anims` holds the shared animations (idle, walk, sit,\n' +
  '   wheelchair). Bundled as text so the 3D view also works when the game is opened from disk. */\n' +
  'window.BTS_PATRON_MODELS = {\n' + Object.entries(out).map(([k, v]) => '  ' + JSON.stringify(k) + ': "' + v + '"').join(',\n') + '\n};\n';
fs.writeFileSync(path.join(ROOT, 'js', 'patron-models.js'), js);
console.log('wrote js/patron-models.js,', js.length, 'bytes');
