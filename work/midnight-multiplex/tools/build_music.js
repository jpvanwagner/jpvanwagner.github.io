#!/usr/bin/env node
/* ============================================================================
 *  tools/build_music.js  —  `npm run music`
 * ----------------------------------------------------------------------------
 *  The music lives in music/songs/<id>.js — ZzFXM Tracker song files (open and
 *  save them in https://keithclark.github.io/ZzFXM/tracker/). The game fetches
 *  those directly over http(s), but from file:// fetch is blocked, so it loads
 *  music/songs/offline/<id>.js instead: a generated one-liner,
 *      MMMusic.register("<id>", <the song array>);
 *  This script (re)writes those copies and checks every song first:
 *    - it parses the way ZzFXM Tracker parses (so a broken file fails HERE, not
 *      in the tracker or the game),
 *    - every song listed in SONGS in music/musicPlayer.js has a file, and every
 *      file is listed (a warning — an unlisted song still works via play()).
 *
 *  Run it after saving a song from the tracker. `npm run demo` runs it too.
 *  --check : change nothing; exit 1 if any offline copy is missing or stale
 *            (`npm run check` uses this).
 * ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SONGS_DIR = path.join(ROOT, 'music', 'songs');
const OFF_DIR = path.join(SONGS_DIR, 'offline');
const CHECK = process.argv.includes('--check');

// ZzFXM Tracker's loader (zzfxm-song-encoder/decode.js): "short JSON" → JSON.
function parseSong(text) {
  const safe = text.replace(/\[,/g, '[null,').replace(/,,\]/g, ',null]').replace(/,\s*(?=[,\]])/g, ',null')
    .replace(/([\[,]-?)(?=\.)/g, '$10').replace(/-\./g, '-0.');
  return JSON.parse(safe, (k, v) => (v === null ? undefined : v));
}
// The tracker's validateSong(), condensed.
function validate(song) {
  const num = v => typeof v === 'number' || v === undefined;
  if (!Array.isArray(song) || song.length < 3) return 'not a ZzFXM song array';
  const [ins, pats, seq, bpm, meta] = song;
  if (!Array.isArray(ins) || ins.some(i => !Array.isArray(i) || [...i].some(v => !num(v)))) return 'bad instrument list';
  if (!Array.isArray(pats) || pats.some(p => !Array.isArray(p) || p.some(c => !Array.isArray(c) || [...c].some(v => !num(v))))) return 'bad pattern list';
  if (!Array.isArray(seq) || seq.some(v => typeof v !== 'number' || !pats[v])) return 'bad sequence';
  if (bpm !== undefined && typeof bpm !== 'number') return 'bad speed';
  if (meta !== undefined && (typeof meta !== 'object' || Array.isArray(meta))) return 'bad metadata';
  for (const p of pats) for (const c of p) if (!ins[c[0] || 0]) return 'a channel uses instrument ' + c[0] + ', which does not exist';
  return null;
}

const listed = (() => {
  const src = fs.readFileSync(path.join(ROOT, 'music', 'musicPlayer.js'), 'utf8');
  const block = /const SONGS = \{([\s\S]*?)\n  \};/.exec(src);
  return block ? [...block[1].matchAll(/'([a-z0-9-]+)'\s*:/g)].map(m => m[1]) : [];
})();
const files = fs.readdirSync(SONGS_DIR).filter(f => f.endsWith('.js')).map(f => f.slice(0, -3)).sort();

let bad = 0, stale = 0, wrote = 0;
for (const id of listed) if (!files.includes(id)) { console.error('✗ ' + id + ': listed in musicPlayer.js SONGS but music/songs/' + id + '.js is missing'); bad++; }
for (const id of files) {
  const text = fs.readFileSync(path.join(SONGS_DIR, id + '.js'), 'utf8').trim();
  let song;
  try { song = parseSong(text); } catch (e) { console.error('✗ ' + id + ': ZzFXM Tracker could not open this file (' + e.message + ')'); bad++; continue; }
  const err = validate(song);
  if (err) { console.error('✗ ' + id + ': ' + err); bad++; continue; }
  if (!listed.includes(id)) console.warn('! ' + id + ': not in SONGS (music/musicPlayer.js) — add it there for its volume/loop settings and the sound test');
  const out = '/* GENERATED by tools/build_music.js from music/songs/' + id + '.js — do not edit; edit the song in ZzFXM Tracker and run `npm run music`. */\n' +
    'MMMusic.register(' + JSON.stringify(id) + ', ' + text + ');\n';
  const dst = path.join(OFF_DIR, id + '.js');
  const cur = fs.existsSync(dst) ? fs.readFileSync(dst, 'utf8') : null;
  if (cur === out) continue;
  if (CHECK) { console.error('✗ ' + id + ': music/songs/offline/' + id + '.js is ' + (cur == null ? 'missing' : 'out of date') + ' — run `npm run music`'); stale++; continue; }
  fs.mkdirSync(OFF_DIR, { recursive: true });
  fs.writeFileSync(dst, out); wrote++;
}
// offline copies whose song file is gone
if (fs.existsSync(OFF_DIR)) for (const f of fs.readdirSync(OFF_DIR)) {
  if (f.endsWith('.js') && !files.includes(f.slice(0, -3))) {
    if (CHECK) { console.error('✗ offline/' + f + ' has no song file — run `npm run music`'); stale++; }
    else { fs.unlinkSync(path.join(OFF_DIR, f)); console.log('removed offline/' + f); }
  }
}
if (bad || stale) process.exit(1);
console.log(CHECK ? 'music: ' + files.length + ' songs OK, offline copies up to date' : 'music: ' + files.length + ' songs OK, ' + wrote + ' offline cop' + (wrote === 1 ? 'y' : 'ies') + ' written');
